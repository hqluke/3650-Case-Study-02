// Measures target sizes at phone and desktop widths and runs axe on every step and error state.
// Writes ../target-size-audit.md and ../axe-results.md. Serve the site first:
//   python3 -m http.server 8765 --directory docs
// Run: node prototype_spec/scripts/audit.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const here = new URL('.', import.meta.url);
const B = 'http://localhost:8765', U = `${B}/?now=2026-11-06T09:30`;
const MEASURE = readFileSync(new URL('measure-targets.js', here), 'utf8').replace(/^\/\/.*\n/gm, '');
const AXE = readFileSync(new URL('axe-check.js', here), 'utf8').replace(/^\/\/.*\n/gm, '');
const today = new Date().toISOString().slice(0, 10);

const axi = (...args) => execFileSync('chrome-devtools-axi', args, { encoding: 'utf8' });
const sleep = ms => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
const open = url => { axi('open', url); sleep(1500); };
const run = js => axi('eval', `() => { ${js}; return 1 }`);
const evalJson = js => JSON.parse(JSON.parse(axi('eval', js).match(/^result: (.*)$/m)[1]));
const review = () => run("document.querySelectorAll('.tee-card')[3].click(); document.querySelector('#other-policy-toggle').click(); document.querySelector('#pay-button').click()");

const sizes = [];
for (const width of [390, 1280]) {
  axi('resize', String(width), '900');
  open(U); run('sessionStorage.clear()'); open(U);
  run("const t = document.querySelector('#filters-toggle'); if (innerWidth < 820 && t.getAttribute('aria-expanded') === 'false') t.click()");
  for (const step of ['Find a time', 'Review and pay']) {
    if (step === 'Review and pay') review();
    for (const r of evalJson(MEASURE)) {
      const ok = r.width >= 44 && r.height >= 44 && r.gap >= 8;
      sizes.push(`| ${width} | ${step} | ${r.name} | ${r.count} | ${r.width} x ${r.height} | ${r.gap} | ${ok ? 'Pass' : '**Fail**'} |`);
    }
  }
}
writeFileSync(new URL('../target-size-audit.md', here), `## Target Size Audit

Generated by \`scripts/audit.mjs\` on ${today}. Sizes are the smallest of each kind of target, in CSS pixels. Gap is the smallest distance from that kind of target to any other target. The bar is 44 x 44 with at least 8 px between targets.

| Width | Step | Target | Count | Smallest size | Smallest gap | Result |
| --- | --- | --- | --- | --- | --- | --- |
${sizes.join('\n')}
`);

axi('resize', '1280', '900');
const axeRows = [];
const check = label => {
  const r = evalJson(AXE);
  axeRows.push(`| ${label} | ${r.passes} | ${r.violations.join(', ') || 'None'} |`);
};
open(U); check('Find a time');
run("document.querySelectorAll('input[name=courses]').forEach(b => b.click())"); sleep(300); check('No course picked (error)');
open(`${B}/?date=2026-11-06&holes=18&players=4&tod=morning&courses=dp&now=2026-11-06T09:30`); check('Empty results');
open(U); review(); check('Review with every error showing');
run("const f = document.querySelector('#booking-form'); f.querySelector('[name=holes]:not(:disabled)').click(); f.querySelector('[name=cart][value=no]').click(); f.name.value = 'Luke'; f.email.value = 'luke@example.com'; document.querySelector('[name=latency][value=fast]').click(); document.querySelector('[name=outcome][value=network]').click(); document.querySelector('#pay-button').click()");
sleep(1000); check('Payment failed');
run("document.querySelector('#pay-button').click()"); sleep(1000); check('Confirmation');
open(`${B}/states.html`); check('Component states page');
writeFileSync(new URL('../axe-results.md', here), `## axe-core Results

Generated by \`scripts/audit.mjs\` on ${today} with axe-core 4.10.2, running the WCAG 2.0 and 2.1 A and AA rules plus best practices.

| Page state | Rules passed | Violations |
| --- | --- | --- |
${axeRows.join('\n')}
`);
console.log('Wrote target-size-audit.md and axe-results.md');
